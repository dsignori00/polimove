function plotClassifiedDetections(stamp,values,max_det,color,name, ...
        marker_size,ground_truth_enabled,correct_mask,false_positive_mask)
%PLOTCLASSIFIEDDETECTIONS Plot radar detections with optional TP/FP styling.

values = safe_cols(values,max_det);
if isvector(stamp) && numel(stamp) == size(values,1)
    stamp = repmat(stamp(:),1,size(values,2));
else
    stamp = safe_cols(stamp,max_det);
end

if ground_truth_enabled
    correct_mask = safe_cols(correct_mask,max_det);
    false_positive_mask = safe_cols(false_positive_mask,max_det);

    correct_values = values;
    correct_values(~correct_mask) = NaN;
    false_positive_values = values;
    false_positive_values(~false_positive_mask) = NaN;

    plot(stamp,correct_values,'o','MarkerFaceColor',color, ...
        'MarkerEdgeColor',color,'MarkerSize',marker_size, ...
        'HandleVisibility','off');
    plot(stamp,false_positive_values,'o', ...
        'MarkerFaceColor','none','MarkerEdgeColor',color, ...
        'MarkerSize',marker_size,'HandleVisibility','off');
    plot(NaN,NaN,'o','MarkerFaceColor',color, ...
        'MarkerEdgeColor',color,'MarkerSize',marker_size, ...
        'DisplayName',name + " - TP");
    plot(NaN,NaN,'o','MarkerFaceColor','none', ...
        'MarkerEdgeColor',color,'MarkerSize',marker_size, ...
        'DisplayName',name + " - FP");
else
    plot(stamp,values,'o','MarkerFaceColor',color, ...
        'MarkerEdgeColor',color,'MarkerSize',marker_size, ...
        'HandleVisibility','off');
    plot(NaN,NaN,'o','MarkerFaceColor',color, ...
        'MarkerEdgeColor',color,'MarkerSize',marker_size, ...
        'DisplayName',name);
end
end
